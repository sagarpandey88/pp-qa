export interface ScenarioDefinition {
  id?: string;
  title: string;
  targetAppType: string; // 'model_driven' | 'canvas' | 'copilot'
  targetAppName?: string;
  preconditions?: string[];
  steps: string[];
  expectedAssertions: string[];
}

export interface SynthesisOptions {
  suiteTitle: string;
  targetAppType: string;
  targetAppName?: string;
  environmentUrl?: string;
  scenarios: ScenarioDefinition[];
  useStepsBlock?: boolean;
}

export function synthesizePlaywrightTestSuite(options: SynthesisOptions): string {
  const { suiteTitle, targetAppType, targetAppName, environmentUrl, scenarios, useStepsBlock = true } = options;

  const appName = targetAppName || 'Customer Service Hub';
  const envUrl = environmentUrl || 'https://org.crm.dynamics.com';

  let code = `import { test, expect } from '@playwright/test';
import {
  AppProvider,
  LoginPage,
  ModelDrivenAppPage,
  GridComponent,
  FormComponent,
  CopilotChatComponent,
} from '../templates/pom';

/**
 * Test Suite: ${suiteTitle}
 * Target App: ${appName} (${targetAppType})
 * Generated by pp-qa Agentic Test Synthesizer
 */
test.describe('${suiteTitle.replace(/'/g, "\\'")}', () => {
  let appProvider: AppProvider;
  let loginPage: LoginPage;
  let modelApp: ModelDrivenAppPage;
  let grid: GridComponent;
  let form: FormComponent;
  let copilot: CopilotChatComponent;

  test.beforeEach(async ({ page }) => {
    appProvider = new AppProvider(page);
    loginPage = new LoginPage(page);
    modelApp = new ModelDrivenAppPage(page);
    grid = new GridComponent(page);
    form = new FormComponent(page);
    copilot = new CopilotChatComponent(page);

    // Prestep: Navigate to target Power Platform app environment & handle authentication
    const appUrl = process.env.PP_APP_URL || '${envUrl}';
    await appProvider.navigateToApp(appUrl, { targetAppName: '${appName}' });
    await appProvider.waitForAppReady();
  });
`;

  for (const scenario of scenarios) {
    const safeTitle = scenario.title.replace(/'/g, "\\'");
    code += `
  test('${safeTitle}', async ({ page }) => {
`;

    if (scenario.preconditions && scenario.preconditions.length > 0) {
      code += `    // Preconditions:\n`;
      for (const pre of scenario.preconditions) {
        code += `    // - ${pre}\n`;
      }
    }

    code += `\n    // --- Execution Steps ---\n`;
    for (const step of scenario.steps) {
      const stepLower = step.toLowerCase();
      const safeStep = step.replace(/'/g, "\\'");
      const quoteMatches = [...step.matchAll(/["']([^"']+)["']/g)].map((m) => m[1]);

      let actionCode = '';

      if (stepLower.includes('login') || stepLower.includes('sign in') || stepLower.includes('authenticate')) {
        actionCode = `await loginPage.login();`;
      } else if (stepLower.includes('new') || stepLower.includes('+ new')) {
        actionCode = `await modelApp.clickCommandButton('New');`;
      } else if (stepLower.includes('save & close') || stepLower.includes('save and close')) {
        actionCode = `await modelApp.saveAndClose();`;
      } else if (stepLower.includes('save')) {
        actionCode = `await modelApp.save();`;
      } else if (stepLower.includes('deactivate')) {
        actionCode = `await modelApp.clickCommandButton('Deactivate');`;
      } else if (stepLower.includes('activate')) {
        actionCode = `await modelApp.clickCommandButton('Activate');`;
      } else if (stepLower.includes('delete')) {
        actionCode = `await modelApp.clickCommandButton('Delete');`;
      } else if (stepLower.includes('refresh')) {
        actionCode = `await modelApp.clickCommandButton('Refresh');`;
      } else if (stepLower.includes('switch to') && stepLower.includes('tab')) {
        const tabName = quoteMatches[0] || (stepLower.includes('related') ? 'Related' : 'General');
        actionCode = `await modelApp.switchTab('${tabName}');`;
      } else if (stepLower.includes('open') && (stepLower.includes('row') || stepLower.includes('grid') || stepLower.includes('record') || stepLower.includes('locate'))) {
        const term = quoteMatches[0] || '';
        actionCode = term ? `await grid.search('${term}');\n      await grid.openRow(0);` : `await grid.openRow(0);`;
      } else if (stepLower.includes('select') && (stepLower.includes('row') || stepLower.includes('grid') || stepLower.includes('checkbox') || stepLower.includes('record'))) {
        const term = quoteMatches[0] || '';
        actionCode = term ? `await grid.selectRow('${term}');` : `await grid.selectRow(0);`;
      } else if (stepLower.includes('search') || stepLower.includes('filter') || stepLower.includes('quick find')) {
        const queryTerm = quoteMatches[0] || 'Contoso';
        actionCode = `await grid.search('${queryTerm}');`;
      } else if (stepLower.includes('lookup') || stepLower.includes('combobox')) {
        const fieldName = quoteMatches[0] ? quoteMatches[0].toLowerCase().replace(/\s+/g, '') : 'parentcustomerid';
        const val = quoteMatches[1] || quoteMatches[0] || 'Fabrikam';
        actionCode = `await form.setLookupValue('${fieldName}', '${val}');`;
      } else if (
        stepLower.includes('dropdown') ||
        stepLower.includes('picklist') ||
        stepLower.includes('option set') ||
        (stepLower.includes('select') && (stepLower.includes('option') || stepLower.includes('choice')))
      ) {
        const fieldName = quoteMatches.length >= 2 ? quoteMatches[0].toLowerCase().replace(/\s+/g, '') : 'statuscode';
        const optVal = quoteMatches[1] || quoteMatches[0] || 'Active';
        actionCode = `await form.selectOption('${fieldName}', '${optVal}');`;
      } else if (
        stepLower.includes('site map') ||
        stepLower.includes('sitemap') ||
        stepLower.includes('subarea') ||
        stepLower.includes('navigate to') ||
        (stepLower.includes('select') && (stepLower.includes('table') || stepLower.includes('entity')))
      ) {
        const subArea = quoteMatches[0] || (stepLower.includes('employee') ? 'Employees' : 'Home');
        actionCode = `await modelApp.navigateToSubArea('${subArea}');`;
      } else if (
        stepLower.includes('view') &&
        (stepLower.includes('switch') || stepLower.includes('set to') || stepLower.includes('ensure') || stepLower.includes('change view') || stepLower.includes('select'))
      ) {
        const viewName = quoteMatches[0] || (stepLower.includes('inactive') ? 'Inactive Employees' : 'Active Employees');
        actionCode = `await grid.switchView('${viewName}');`;
      } else if (
        stepLower.includes('fill') ||
        stepLower.includes('enter') ||
        stepLower.includes('type') ||
        stepLower.includes('set') ||
        stepLower.includes('append') ||
        stepLower.includes('paste') ||
        stepLower.includes('change') ||
        stepLower.includes('update')
      ) {
        const schemaMatch = step.match(/\b([a-zA-Z0-9_]+_[a-zA-Z0-9_]+)\b/);
        const fieldName = schemaMatch
          ? schemaMatch[1]
          : quoteMatches.length >= 2
            ? quoteMatches[0].toLowerCase().replace(/\s+/g, '')
            : 'name';
        const val = quoteMatches.length >= 2 ? quoteMatches[1] : (quoteMatches[0] || 'Sample Test Record');
        actionCode = `await form.setTextInput('${fieldName}', '${val}');`;
      } else if (
        stepLower.includes('owner') ||
        stepLower.includes('createdon') ||
        stepLower.includes('modifiedon') ||
        stepLower.includes('read-only') ||
        stepLower.includes('populated')
      ) {
        const schemaMatch = step.match(/\b([a-zA-Z0-9_]+_[a-zA-Z0-9_]+|ownerid|createdon|modifiedon|createdby|modifiedby)\b/i);
        const fieldName = schemaMatch ? schemaMatch[1].toLowerCase() : (stepLower.includes('owner') ? 'ownerid' : 'createdon');
        actionCode = `await form.assertFieldValue('${fieldName}');`;
      } else if (stepLower.includes('confirm') || stepLower.includes('dialog')) {
        const btn = quoteMatches[0] || 'OK';
        actionCode = `await modelApp.confirmDialog('${btn}');`;
      } else if (
        stepLower.includes('greeting') ||
        stepLower.includes('copilot') ||
        stepLower.includes('prompt') ||
        stepLower.includes('send')
      ) {
        const promptText = quoteMatches[0] || 'Hi, can you help me?';
        actionCode = `await copilot.sendMessage('${promptText}');`;
      } else {
        actionCode = `await appProvider.waitForAppReady();`;
      }

      if (useStepsBlock) {
        code += `    await test.step('${safeStep}', async () => {\n`;
        code += `      ${actionCode}\n`;
        code += `    });\n`;
      } else {
        code += `    // Step: ${step}\n`;
        code += `    ${actionCode}\n`;
      }
    }

    code += `\n    // --- Assertions & Verifications ---\n`;
    for (const assertion of scenario.expectedAssertions) {
      const assertLower = assertion.toLowerCase();
      const safeAssert = assertion.replace(/'/g, "\\'");
      const quoteMatches = [...assertion.matchAll(/["']([^"']+)["']/g)].map((m) => m[1]);

      let assertCode = '';

      if (assertLower.includes('adaptive card')) {
        assertCode = `await copilot.assertAdaptiveCardVisible();`;
      } else if (
        assertLower.includes('copilot') ||
        assertLower.includes('generative') ||
        assertLower.includes('bot') ||
        assertLower.includes('response')
      ) {
        const term = quoteMatches[0] || 'Hello';
        assertCode = `await copilot.assertResponseContains('${term}');`;
      } else if (
        assertLower.includes('grid') ||
        assertLower.includes('listed') ||
        assertLower.includes('contains') ||
        assertLower.includes('view')
      ) {
        const term = quoteMatches[0] || 'Fabrikam Aerospace';
        assertCode = `await grid.assertRowContains('${term}');`;
      } else if (assertLower.includes('error') || assertLower.includes('validation') || assertLower.includes('required')) {
        assertCode = `await expect(page.locator('[data-id="error-dialog"], .ms-errorMessage, [role="alert"]')).toBeVisible({ timeout: 5000 });`;
      } else {
        assertCode = `await expect(page.locator('[data-id="error-dialog"]')).not.toBeVisible();`;
      }

      if (useStepsBlock) {
        code += `    await test.step('Verify: ${safeAssert}', async () => {\n`;
        code += `      ${assertCode}\n`;
        code += `    });\n`;
      } else {
        code += `    // Expect: ${assertion}\n`;
        code += `    ${assertCode}\n`;
      }
    }

    code += `  });\n`;
  }

  code += `});\n`;

  return code;
}
